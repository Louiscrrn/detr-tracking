"""Statistics on MOT17 pedestrian boxes: image border, visibility, size.

Reads the COCO annotations from `scripts/prepare_mot17.py` and writes docs/DATA_STATS.md
(tables per split and per sequence) and outputs/data_stats.json.

Usage: uv run python scripts/data_stats.py
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

SPLITS = ("train_half", "val_half")
VIS_BINS = [(0.0, 0.1), (0.1, 0.25), (0.25, 0.5), (0.5, 0.75), (0.75, 1.01)]
INPUT_RES = 512  # RF-DETR Small input side: a box h px tall becomes h * 512 / image height


def box_table(anns: list[dict], images: dict[int, dict]) -> dict:
    """Per-box arrays for pedestrian (non-ignore) annotations."""
    rows = defaultdict(list)
    for a in anns:
        if a["iscrowd"]:
            continue
        im = images[a["image_id"]]
        iw, ih = im["width"], im["height"]
        x, y, w, h = a["bbox"]
        cx, cy = x + w / 2, y + h / 2
        inside = max(0, min(x + w, iw) - max(x, 0)) * max(0, min(y + h, ih) - max(y, 0)) / (w * h)
        rows["image_id"].append(a["image_id"])
        rows["video"].append(im["video_id"])
        rows["crossing"].append(x < 0 or y < 0 or x + w > iw or y + h > ih)
        rows["centre_out"].append(not (0 <= cx <= iw and 0 <= cy <= ih))
        rows["too_big"].append(w > iw or h > ih)
        rows["outside_frac"].append(1 - inside)
        rows["top"].append(y < 0)
        rows["bottom"].append(y + h > ih)
        rows["left"].append(x < 0)
        rows["right"].append(x + w > iw)
        rows["visibility"].append(a["visibility"])
        rows["height_in"].append(h * INPUT_RES / ih)
    return {k: np.array(v) for k, v in rows.items()}


def summarise(t: dict, n_images: int, n_ignore: int) -> dict:
    n = len(t["crossing"])
    clamped = t["centre_out"] | t["too_big"]
    crossing = t["crossing"]
    out = {
        "images": n_images,
        "boxes": n,
        "ignore_regions": n_ignore,
        "crossing": float(crossing.mean()),
        "crossing_images": float(len(set(t["image_id"][crossing])) / n_images),
        "centre_out": float(t["centre_out"].mean()),
        "too_big": float((t["too_big"] & ~t["centre_out"]).mean()),
        "clamped_by_rule": float(clamped.mean()),
        "kept_whole_among_crossing": float((crossing & ~clamped).sum() / max(crossing.sum(), 1)),
        "outside_frac_median_crossing": float(np.median(t["outside_frac"][crossing]))
        if crossing.any()
        else 0.0,
        "sides": {s: float(t[s].mean()) for s in ("top", "bottom", "left", "right")},
        "visibility_mean": float(t["visibility"].mean()),
        "visibility_bins": {
            f"[{lo}, {min(hi, 1.0)}{']' if hi > 1 else ')'}": float(
                ((t["visibility"] >= lo) & (t["visibility"] < hi)).mean()
            )
            for lo, hi in VIS_BINS
        },
        "height_at_512_median": float(np.median(t["height_in"])),
        "height_at_512_below_32": float((t["height_in"] < 32).mean()),
    }
    return out


def pct(x: float) -> str:
    return f"{100 * x:.1f} %"


def write_markdown(stats: dict, path: Path) -> None:
    lines = [
        "# MOT17 data statistics",
        "",
        "Pedestrian boxes (class 1, flag 1) of the MOT17 train sequences (FRCNN folders),",
        "split by frame into `train_half` / `val_half`. Ignore regions (person on vehicle,",
        "static person, distractor, reflection, flag 0) are counted apart and excluded from",
        "the box statistics.",
        "Generated by `scripts/data_stats.py` (`make stats`).",
        "",
        "Definitions:",
        "",
        "- *crossing*: the box extends past the image border (MOT17 annotates the full person).",
        "- *centre out*: the box centre lies outside the image; a DETR cannot predict it.",
        "- *too big*: centre inside but width or height larger than the image;",
        "  not predictable either.",
        "- *clamped by rule*: centre out or too big; clamped to the image for training,",
        "  every other box is kept whole (see [DECISIONS.md](DECISIONS.md), D3).",
        "- *height @512*: box height once the image is resized to RF-DETR Small's 512 px input.",
        "",
        "## Image border, per split",
        "",
        "| | images | boxes | ignore regions | crossing | images with a crossing box "
        "| centre out | too big | clamped by rule | crossing kept whole "
        "| median part outside (crossing) |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name, s in stats["splits"].items():
        lines.append(
            f"| {name} | {s['images']} | {s['boxes']} | {s['ignore_regions']} "
            f"| {pct(s['crossing'])} "
            f"| {pct(s['crossing_images'])} | {pct(s['centre_out'])} | {pct(s['too_big'])} "
            f"| {pct(s['clamped_by_rule'])} | {pct(s['kept_whole_among_crossing'])} "
            f"| {pct(s['outside_frac_median_crossing'])} |"
        )
    lines += [
        "",
        "Side crossed (share of all boxes; a box can cross two sides):",
        "",
        "| | top | bottom | left | right |",
        "|---|---|---|---|---|",
    ]
    for name, s in stats["splits"].items():
        sd = s["sides"]
        lines.append(
            f"| {name} | {pct(sd['top'])} | {pct(sd['bottom'])} | {pct(sd['left'])} "
            f"| {pct(sd['right'])} |"
        )
    bins = list(next(iter(stats["splits"].values()))["visibility_bins"])
    lines += [
        "",
        "## Visibility, per split",
        "",
        "Visibility is MOT17's ratio of the box that is visible (occlusion and image border).",
        "",
        "| | mean | " + " | ".join(bins) + " |",
        "|---|---|" + "---|" * len(bins),
    ]
    for name, s in stats["splits"].items():
        vb = s["visibility_bins"]
        lines.append(
            f"| {name} | {s['visibility_mean']:.2f} | "
            + " | ".join(pct(vb[b]) for b in bins)
            + " |"
        )
    lines += [
        "",
        "## Per sequence (train_half + val_half)",
        "",
        "| sequence | images | boxes | crossing | centre out | too big | clamped by rule "
        "| visibility mean | visibility < 0.25 | height @512 median | height @512 < 32 px |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name, s in stats["sequences"].items():
        low = s["visibility_bins"]["[0.0, 0.1)"] + s["visibility_bins"]["[0.1, 0.25)"]
        lines.append(
            f"| {name} | {s['images']} | {s['boxes']} | {pct(s['crossing'])} "
            f"| {pct(s['centre_out'])} | {pct(s['too_big'])} | {pct(s['clamped_by_rule'])} "
            f"| {s['visibility_mean']:.2f} | {pct(low)} | {s['height_at_512_median']:.0f} px "
            f"| {pct(s['height_at_512_below_32'])} |"
        )
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--ann-dir", type=Path, default=Path("data/mot17/annotations"))
    parser.add_argument("--md", type=Path, default=Path("docs/DATA_STATS.md"))
    parser.add_argument("--json", type=Path, default=Path("outputs/data_stats.json"))
    args = parser.parse_args()

    stats: dict = {"splits": {}, "sequences": {}}
    per_seq: dict = defaultdict(lambda: {"anns": [], "images": {}, "ignore": 0})
    for split in SPLITS:
        coco = json.loads((args.ann_dir / f"{split}.json").read_text())
        images = {im["id"]: im for im in coco["images"]}
        videos = {v["id"]: v["name"] for v in coco["videos"]}
        n_ignore = sum(a["iscrowd"] for a in coco["annotations"])
        table = box_table(coco["annotations"], images)
        stats["splits"][split] = summarise(table, len(images), n_ignore)
        for im in coco["images"]:
            per_seq[videos[im["video_id"]]]["images"][im["id"]] = im
        for a in coco["annotations"]:
            seq = per_seq[videos[images[a["image_id"]]["video_id"]]]
            seq["anns"].append(a)
            seq["ignore"] += a["iscrowd"]
    for name in sorted(per_seq):
        seq = per_seq[name]
        table = box_table(seq["anns"], seq["images"])
        stats["sequences"][name] = summarise(table, len(seq["images"]), seq["ignore"])

    args.json.parent.mkdir(parents=True, exist_ok=True)
    args.json.write_text(json.dumps(stats, indent=2))
    write_markdown(stats, args.md)
    print(f"wrote {args.md} and {args.json}")


if __name__ == "__main__":
    main()
